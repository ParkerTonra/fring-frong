// Fring Frong's desktop sprites: the terminal's own frogs (hooks/pong.ts), each of their pixels scaled up to a 2 x 2 or
// 3 x 3 block, then lightly refined: a dark outline, one highlight and one shade on the green, a catchlight in each
// pupil, the blocks' outer corners rounded at 3x. The same wide, short frog: square eyes on top, the brown mouth band,
// the blue shirt. DESK_SIZE picks the scale the band draws. Pure data and no imports, so another mod (now-playing) can
// take this file as it is.
//
// MADE BY tools/make-sprites.ts (deno run --allow-read --allow-write tools/make-sprites.ts) from
// tools/sprites.template.txt: change the originals or the recipe there, not the rows here.
//
// Each sprite is rows of palette letters ('.' see-through), one outline pixel round the scaled original. A frog's
// pixel is 4 / scale view units (a terminal sprite pixel is 4), so a frog fills the terminal's 32 x 24 unit box plus its
// outline; the fans and the ball come from half-size terminal pixels (2 units), so theirs are 2 / scale.

/** A scale: each terminal pixel becomes a scale x scale block. */
export type SpriteSize = 2 | 3
/** The scale the desktop band draws its sprites at. */
export const DESK_SIZE: SpriteSize = 3
/** View units a frog (or froglet) sprite pixel takes at `size`. */
export const unit = (size: SpriteSize): number => 4 / size
/** View units a fan, ball or star pixel takes at `size` (they come from half-size terminal pixels). */
export const fineUnit = (size: SpriteSize): number => 2 / size

export const SPRITE_PALETTE: Readonly<Record<string, number>> = {
  O: 0x173016, // outline, the terminal's dark green (closed lids, the head's corners)
  S: 0x356f28, // shade green
  G: 0x4e9a3a, // green
  L: 0x6fb44f, // highlight green
  W: 0xf2f2f2, // eye white, catchlight
  K: 0x101010, // pupil, open mouth
  R: 0x8a4a22, // mouth band
  o: 0x0c1f5c, // shirt outline
  B: 0x1f4fd8, // shirt
  T: 0xe0607a, // tongue
  r: 0x8a2a3f, // tongue outline
  Y: 0xffd84a, // stars, a cheering fan's eyes
  h: 0xffffff, // ball highlight
  c: 0xfff2cc, // ball
  e: 0xd4c08f, // ball shade
}

